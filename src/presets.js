/** The current matrix as the `rules` array literal of a preset (2 decimals). */
export function formatRules(rules) {
    const n = rules.numTypes;
    const rows = [];
    for (let i = 0; i < n; i++) {
        const row = Array.from(rules.data.subarray(i * n, (i + 1) * n), (v) => Math.round(v * 100) / 100);
        rows.push(`    [${row.join(', ')}],`);
    }
    return `[\n${rows.join('\n')}\n]`;
}
